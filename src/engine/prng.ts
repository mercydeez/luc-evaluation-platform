/**
 * Seeded pseudo-random generator.
 *
 * Used to make the simulated evaluator reproducible: the same seed string
 * always yields the same sequence, so an unchanged evaluation key always
 * yields an identical verdict. xmur3 hashes the seed string, sfc32 expands it.
 */

function xmur3(str: string): () => number {
  let h = 1779033703 ^ str.length
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353)
    h = (h << 13) | (h >>> 19)
  }
  return () => {
    h = Math.imul(h ^ (h >>> 16), 2246822507)
    h = Math.imul(h ^ (h >>> 13), 3266489909)
    h ^= h >>> 16
    return h >>> 0
  }
}

function sfc32(a: number, b: number, c: number, d: number): () => number {
  return () => {
    a >>>= 0; b >>>= 0; c >>>= 0; d >>>= 0
    let t = (a + b) | 0
    a = b ^ (b >>> 9)
    b = (c + (c << 3)) | 0
    c = (c << 21) | (c >>> 11)
    d = (d + 1) | 0
    t = (t + d) | 0
    c = (c + t) | 0
    return (t >>> 0) / 4294967296
  }
}

/** Returns a deterministic [0,1) generator for the given seed string. */
export function rng(seed: string): () => number {
  const h = xmur3(seed)
  return sfc32(h(), h(), h(), h())
}
